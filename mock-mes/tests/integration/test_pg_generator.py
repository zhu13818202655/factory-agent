@pytest.mark.asyncio
async def test_invariants_hold_on_postgres_data(migrated_db: str) -> None:
    async with await connect_db(migrated_db) as connection:
        # je = sl × price across the three wage sources — checked in SQL so the
        # assertion stays fast at factory scale (hundreds of thousands of rows).
        cursor = await connection.execute(
            """
            SELECT
              (SELECT count(*) FROM mock_barcode_cl
                WHERE je <> sl * (payload->>'price')::numeric) AS bad_scan,
              (SELECT count(*) FROM mock_dg_cl
                WHERE je <> sl * (payload->>'price')::numeric) AS bad_hanging,
              (SELECT count(*) FROM mock_pin_feng
                WHERE je <> sl * (payload->>'price')::numeric) AS bad_manual,
              (SELECT count(*) FROM mock_barcode_cl) AS scan_rows
            """
        )
        tally = await cursor.fetchone()
        assert tally is not None
        assert tally["bad_scan"] == 0
        assert tally["bad_hanging"] == 0
        assert tally["bad_manual"] == 0
        assert tally["scan_rows"] > 0

        # Scanned worktypes are within the known worktype set.
        cursor = await connection.execute("SELECT DISTINCT worktype FROM mock_barcode")
        scanned = {str(row["worktype"]) for row in await cursor.fetchall()}
        assert scanned <= {"WT01", "WT02", "WT03"}

        # Wsk (unscanned) worktypes are part of the same set.
        cursor = await connection.execute("SELECT DISTINCT worktype FROM mock_wsk")
        unscanned = {str(row["worktype"]) for row in await cursor.fetchall()}
        assert unscanned <= {"WT01", "WT02", "WT03"}


@pytest.mark.asyncio
async def test_sql_row_level_filtering_visibility(migrated_db: str) -> None:
    """Company/role tiers are enforced in SQL: 99 whole, 02 bound depts, 01 own
    小组 (on personal uid rows), 00 own data only."""
    app = create_app(
        MockMesSettings(
            environment="test",
            database_url=SecretStr(migrated_db),
            virtual_now=datetime.fromisoformat("2026-08-21T08:00:00+00:00"),
            data_start=TEST_WINDOW_START,
            data_end=TEST_WINDOW_END,
        )
    )
    await app.state.db.open()
    try:
        transport = ASGITransport(app=app)
        async with AsyncClient(transport=transport, base_url="http://test") as client:
            token = (await client.post("/api/system/token", json={"app_key": "APPKEY-A"})).json()[
                "result"
            ]
            params = {
                "app_key": token["appkey"],
                "timestamp": token["timestamp"],
                "sign": token["sign"],
                "page": 1,
                "size": 200,
                "Uid": "01001",
                "dates": "2026-07-01",
                "datee": "2026-08-31",
            }
            boss = (
                await client.post(
                    "/api/NetYf/Sclzd/YskQuery",
                    json=params,
                    headers={"Authorization": "Bearer MOCK-TOKEN-01009"},
                )
            ).json()["result"]["list"]
            manager = (
                await client.post(
                    "/api/NetYf/Sclzd/YskQuery",
                    json=params,
                    headers={"Authorization": "Bearer MOCK-TOKEN-01008"},
                )
            ).json()["result"]["list"]
            worker = (
                await client.post(
                    "/api/NetYf/Sclzd/YskQuery",
                    json=params,
                    headers={"Authorization": "Bearer MOCK-TOKEN-01001"},
                )
            ).json()["result"]["list"]
            # Leader scope is exercised without a Uid narrowing filter: the
            # group leader (01012, dept-a1 g02) must see only group members.
            leader_params = {k: v for k, v in params.items() if k != "Uid"}
            leader = (
                await client.post(
                    "/api/NetYf/Sclzd/YskQuery",
                    json=leader_params,
                    headers={"Authorization": "Bearer MOCK-TOKEN-01012"},
                )
            ).json()["result"]["list"]
    finally:
        await app.state.db.close()

    assert len(boss) >= len(manager) >= len(worker)
    assert all(row["dept"] == "dept-a1" for row in manager)
    assert all(row["uid"] == "01001" for row in worker)

    # 01 组长 sees only their bound 小组's member rows (SQL group_id subquery).
    async with await connect_db(migrated_db) as connection:
        cursor = await connection.execute(
            "SELECT group_id FROM mock_employee WHERE company = 'COMPANY-A' AND uid = '01012'"
        )
        row = await cursor.fetchone()
        group = str(row["group_id"]) if row else ""
        assert group
        cursor = await connection.execute(
            "SELECT uid FROM mock_employee WHERE company = 'COMPANY-A' AND group_id = %(g)s",
            {"g": group},
        )
        member_uids = {str(item["uid"]) for item in await cursor.fetchall()}
    assert leader
    leader_uids = {str(item["uid"]) for item in leader}
    assert leader_uids <= member_uids
    assert len(leader_uids) > 1


@pytest.mark.asyncio
async def test_pg_unavailable_is_a_loud_error_not_a_fallback() -> None:
    # Explicitly null the URL so the repository-root .env cannot satisfy it.
    with pytest.raises(RuntimeError):
        create_app(MockMesSettings(environment="test", database_url=None))
    # A bad connection must fail at startup, not silently fall back.
    app = create_app(
        MockMesSettings(
            environment="test",
            database_url=SecretStr("postgresql://mock_mes:wrong@127.0.0.1:1/mock_mes"),
            virtual_now=datetime.fromisoformat("2026-08-21T08:00:00+00:00"),
        )
    )
    with pytest.raises(Exception):
        await app.state.db.open()


@pytest.mark.asyncio
async def test_rolling_scans_only_land_on_workdays(migrated_db: str) -> None:
    """Rolling output never lands on weekends/holidays (work calendar)."""
    async with await connect_db(migrated_db) as connection:
        cursor = await connection.execute("SELECT DISTINCT rq FROM mock_barcode_cl")
