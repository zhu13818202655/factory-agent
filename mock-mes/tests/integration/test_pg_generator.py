@pytest.mark.asyncio
async def test_generation_is_idempotent_and_deterministic(migrated_db: str) -> None:
    async with await connect_db(migrated_db) as connection:
        before = {table: await _count(connection, table) for table in _BUSINESS_TABLES}
        settings = MockMesSettings()
        first = await generate_day(connection, settings, date(2026, 8, 10), "run-1")
        second = await generate_day(connection, settings, date(2026, 8, 10), "run-2")
        after = {table: await _count(connection, table) for table in _BUSINESS_TABLES}

    assert first.status == "skipped"  # already generated by the window fill
    assert second.status == "skipped"
    assert before == after  # nothing inserted twice (unique keys + batch ledger)


_BUSINESS_TABLES = (
    "mock_plan",
    "mock_sclzd",
    "mock_sclzd_worktype",
    "mock_barcode",
    "mock_barcode_cl",
    "mock_dg_cl",
    "mock_pin_feng",
    "mock_ysk",
    "mock_wsk",
)


